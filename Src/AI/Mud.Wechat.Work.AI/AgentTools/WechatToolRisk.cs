namespace Mud.Wechat.Work.AI.AgentTools;

/// <summary>
/// 企微工具风险档（剖面 <c>RiskEnumFullName</c> 的消费方契约）。
/// </summary>
/// <remarks>
/// <para>
/// 三档语义与层 1 的 <c>WechatToolRiskVocabulary</c> 同源（<c>read</c> / <c>write</c> / <c>high-risk-write</c>），
/// 成员名须与契约表字面量逐一对应：改名即让生成的契约表失联（编译期报错，故为安全失败）。
/// </para>
/// <para>
/// <b>为什么在层 2 而不在层 1</b>：中性层只认三档<b>词汇</b>（字符串），枚举是「契约表可字面量引用」的编译期形态，
/// 其全名由剖面槽位钉死在本程序集，跨线不共享（各线剖面各持一份）。
/// </para>
/// </remarks>
public enum WechatToolRisk
{
    /// <summary>只读（查询类；默认入只读白名单）。</summary>
    Read = 0,

    /// <summary>受控写（创建/更新类；需显式白名单 + 授权器）。</summary>
    Write = 1,

    /// <summary>高危写（删除/撤回/继承/批量导出类；白名单 + 授权器 + HITL 审批确认门）。</summary>
    HighRiskWrite = 2,
}
