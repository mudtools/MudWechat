namespace Mud.Wechat.Work.DataModels.Security;

/// <summary>
/// 文件/截屏操作类型与来源过滤条件（请求）及记录内操作明细（响应）。
/// </summary>
[HttpJsonSerializable(SerializerClassName = "Security")]
public class FileOperRecordOperation
{
    /// <summary>
    /// 获取或设置操作类型。文件防泄漏常见值：101-上传 103-下载 107-复制 112-转发到企业微信
    /// 113-通过链接下载 114-获取分享链接 121-打开 124-导出文件 134-转发到微信 135-预览
    /// 140-通过邮件分享 150-通过API导出文档 10001-通过下载申请 10002-拒绝下载申请等。
    /// </summary>
    [JsonPropertyName("type")]
    public int? Type { get; set; }

    /// <summary>
    /// 获取或设置操作来源（type 为上传/下载时细分）：401-聊天 402-邮件 403-文档 404-微盘 405-日程
    /// 406-会议 407-审批 408-汇报 409-收集表 410-客户联系 411-上下游 450-收藏 451-文件列表 452-其他。
    /// </summary>
    [JsonPropertyName("source")]
    public int? Source { get; set; }
}
