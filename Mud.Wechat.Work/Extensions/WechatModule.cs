    /// <summary>会话内容存档（开启成员列表域 + 机器人信息域 + 会话同意情况域 + 内部群信息域：官方仅自建，零端点父接口 + 仅自建子接口承载端点；access_token 须由会话内容存档应用 secret 获取。91774 的原生 C SDK 拉取/解密面不在 HTTP SDK 范畴）。</summary>
