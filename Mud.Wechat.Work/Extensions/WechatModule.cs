    /// <summary>JS-SDK（获取企业 jsapi_ticket + 获取应用 jsapi_ticket 两端点三类应用公共面收敛父接口 + 空标记子接口，官方三份文档逐字一致；ticket/get 端点以固定 Query 值 type=agent_config 携带官方鉴权类型；JS-SDK 签名算法为页面/服务器端 SHA-1 约定，不在 HTTP 端点面内）。</summary>
