    /// <summary>政民沟通（配置网格结构域：自建/代开发公共面收敛父接口 + 空标记子接口；获取网格列表官方仅自建开放，独立成族不设代开发子接口；配置事件类别域：自建/代开发公共面收敛父接口 + 空标记子接口；巡查上报族 + 居民上报族：官方仅自建开放，零端点父接口 + 仅自建子接口承载端点；第三方应用官方对全部端点标注暂不支持，不设第三方子接口）。</summary>
